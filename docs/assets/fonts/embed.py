"""Embed the fonts in ../style.css as data URIs.

MyST copies the site stylesheet verbatim and does not publish files it
references,
so the @font-face rules carry the fonts inline. Rerun after changing a font:

    python3 docs/assets/fonts/embed.py
"""

import base64
import re
from pathlib import Path

HERE = Path(__file__).parent
STYLE = HERE.parent / "style.css"
FACES = [
    ("Fraunces", "normal", "300 600", "fraunces.woff2"),
    ("Fraunces", "italic", "300 600", "fraunces-italic.woff2"),
    ("IBM Plex Sans", "normal", "100 700", "ibm-plex-sans.woff2"),
    ("IBM Plex Mono", "normal", "400", "ibm-plex-mono-400.woff2"),
    ("IBM Plex Mono", "normal", "500", "ibm-plex-mono-500.woff2"),
]
BEGIN, END = (
    "/* fonts:begin (generated by fonts/embed.py) */",
    "/* fonts:end */",
)

rules = []
for family, style, weight, name in FACES:
    data = base64.b64encode((HERE / name).read_bytes()).decode()
    rules.append(
        f'@font-face {{ font-family: "{family}"; font-style: {style}; font-weight: {weight}; '  # noqa: E501 -- preserve fixture or report layout
        f'font-display: swap; src: url(data:font/woff2;base64,{data}) format("woff2"); }}'  # noqa: E501 -- preserve fixture or report layout
    )
block = "\n".join([BEGIN, *rules, END])
css = STYLE.read_text()
pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
STYLE.write_text(
    pattern.sub(lambda _: block, css)
    if pattern.search(css)
    else css.rstrip() + "\n\n" + block + "\n"
)
